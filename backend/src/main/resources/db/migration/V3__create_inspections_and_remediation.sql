-- Checklist every inspection is scored against (AC 1.1). Reference data, seeded in V4.
CREATE TABLE checklist_requirements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sort_order INT NOT NULL,
  description VARCHAR(300) NOT NULL,
  CONSTRAINT checklist_requirements_sort_order_key UNIQUE (sort_order)
);

-- A store inspection. A regular inspection is dated the day it starts (AC 1.1). A follow-up
-- (follow_up_of_result_id set) is dated the scheduled day (AC 7.1), then the day it is completed.
CREATE TABLE inspections (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  store_id BIGINT NOT NULL REFERENCES stores (id),
  inspector_id BIGINT NOT NULL REFERENCES users (id),
  inspection_date DATE NOT NULL,
  status VARCHAR(20) NOT NULL,
  follow_up_of_result_id BIGINT,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  submitted_at TIMESTAMP WITH TIME ZONE,
  CONSTRAINT inspections_status_check CHECK (status IN ('DRAFT', 'SUBMITTED')),
  CONSTRAINT inspections_submitted_check CHECK ((status = 'SUBMITTED') = (submitted_at IS NOT NULL))
);
CREATE INDEX inspections_store_idx ON inspections (store_id, inspection_date);

-- One row per checklist requirement per inspection. compliant = FALSE is a flagged issue (AC 2.1).
CREATE TABLE inspection_results (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  inspection_id BIGINT NOT NULL REFERENCES inspections (id) ON DELETE CASCADE,
  requirement_id BIGINT NOT NULL REFERENCES checklist_requirements (id),
  -- NULL while a draft has not marked it yet; submit requires TRUE or FALSE on every row.
  compliant BOOLEAN,
  comment VARCHAR(1000),
  CONSTRAINT inspection_results_requirement_key UNIQUE (inspection_id, requirement_id)
);

-- Added after inspection_results exists, because the two tables reference each other.
ALTER TABLE inspections
  ADD CONSTRAINT inspections_follow_up_of_result_fk
  FOREIGN KEY (follow_up_of_result_id) REFERENCES inspection_results (id) ON DELETE CASCADE;
CREATE INDEX inspections_follow_up_idx ON inspections (follow_up_of_result_id);

-- What the owner must fix for one flagged issue, and by when (US 3). At most one per issue.
CREATE TABLE remediation_tickets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  result_id BIGINT NOT NULL REFERENCES inspection_results (id) ON DELETE CASCADE,
  required_remediation VARCHAR(1000) NOT NULL,
  deadline DATE NOT NULL,
  status VARCHAR(30) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  approved_at TIMESTAMP WITH TIME ZONE,
  -- @Version optimistic lock: every transition updates this row, so concurrent transitions get 409.
  version BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT remediation_tickets_result_key UNIQUE (result_id),
  CONSTRAINT remediation_tickets_status_check CHECK (status IN
    ('OPEN', 'AWAITING_REVIEW', 'REJECTED', 'FOLLOW_UP_SCHEDULED', 'APPROVED')),
  CONSTRAINT remediation_tickets_approved_check CHECK ((status = 'APPROVED') = (approved_at IS NOT NULL))
);

-- The owner's evidence for a ticket (US 5) and the inspector's decision on it (US 6).
-- decision is NULL until reviewed. The state machine plus remediation_tickets.version allow at most
-- one unreviewed row per ticket, even under concurrent requests.
CREATE TABLE remediation_submissions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id BIGINT NOT NULL REFERENCES remediation_tickets (id) ON DELETE CASCADE,
  comment VARCHAR(1000) NOT NULL,
  submitted_at TIMESTAMP WITH TIME ZONE NOT NULL,
  decision VARCHAR(20),
  review_comment VARCHAR(1000),
  reviewed_at TIMESTAMP WITH TIME ZONE,
  CONSTRAINT remediation_submissions_decision_check CHECK (decision IN ('APPROVED', 'REJECTED', 'FOLLOW_UP')),
  CONSTRAINT remediation_submissions_reviewed_check CHECK ((decision IS NULL) = (reviewed_at IS NULL)),
  CONSTRAINT remediation_submissions_reject_comment_check CHECK (decision <> 'REJECTED' OR review_comment IS NOT NULL)
);
CREATE INDEX remediation_submissions_ticket_idx ON remediation_submissions (ticket_id);

-- Pictures of a flagged issue (AC 2.2) or of the owner's fix (AC 5.1). Exactly one parent.
CREATE TABLE photos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  result_id BIGINT REFERENCES inspection_results (id) ON DELETE CASCADE,
  submission_id BIGINT REFERENCES remediation_submissions (id) ON DELETE CASCADE,
  content_type VARCHAR(20) NOT NULL,
  data BYTEA NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT photos_parent_check CHECK ((result_id IS NULL) <> (submission_id IS NULL)),
  CONSTRAINT photos_content_type_check CHECK (content_type IN ('image/jpeg', 'image/png', 'image/webp')),
  CONSTRAINT photos_size_check CHECK (OCTET_LENGTH(data) BETWEEN 1 AND 5242880)
);
CREATE INDEX photos_result_idx ON photos (result_id);
CREATE INDEX photos_submission_idx ON photos (submission_id);
