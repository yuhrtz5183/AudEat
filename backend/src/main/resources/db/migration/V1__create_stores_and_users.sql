CREATE TABLE stores (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  address VARCHAR(200) NOT NULL
);

CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  -- Stored trimmed and lower-cased so uniqueness is case-insensitive.
  email VARCHAR(254) NOT NULL,
  password_hash VARCHAR(100) NOT NULL,
  role VARCHAR(20) NOT NULL,
  store_id BIGINT REFERENCES stores (id),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT users_email_key UNIQUE (email),
  CONSTRAINT users_role_check CHECK (role IN ('INSPECTOR', 'OWNER')),
  -- Store owners belong to exactly one store; inspectors to none.
  CONSTRAINT users_store_check CHECK ((role = 'OWNER') = (store_id IS NOT NULL))
);
